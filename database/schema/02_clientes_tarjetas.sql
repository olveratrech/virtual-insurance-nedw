-- proposito: crear de forma repetible las tablas cliente y tarjeta.
-- conexion requerida: vi_app@etobda_s1

set serveroutput on

declare
    v_usuario     varchar2(128);
    v_contenedor  varchar2(128);

    procedure crear_tabla_si_falta(
        p_tabla     varchar2,
        p_sentencia varchar2
    ) is
        v_existe number;
    begin
        select count(*)
          into v_existe
          from user_tables
         where table_name = upper(p_tabla);

        if v_existe = 0 then
            execute immediate p_sentencia;
            dbms_output.put_line('creada: ' || lower(p_tabla));
        else
            dbms_output.put_line('conservada: ' || lower(p_tabla));
        end if;
    end crear_tabla_si_falta;

    procedure crear_indice_si_falta(
        p_indice    varchar2,
        p_sentencia varchar2
    ) is
        v_existe number;
    begin
        select count(*)
          into v_existe
          from user_indexes
         where index_name = upper(p_indice);

        if v_existe = 0 then
            execute immediate p_sentencia;
            dbms_output.put_line('creado: ' || lower(p_indice));
        else
            dbms_output.put_line('conservado: ' || lower(p_indice));
        end if;
    end crear_indice_si_falta;
begin
    v_usuario := sys_context('USERENV', 'CURRENT_USER');
    v_contenedor := sys_context('USERENV', 'CON_NAME');

    if v_usuario <> 'VI_APP' or v_contenedor <> 'ETOBDA_S1' then
        raise_application_error(
            -20010,
            'conexion incorrecta. se esperaba VI_APP@ETOBDA_S1 y se obtuvo '
            || v_usuario || '@' || v_contenedor
        );
    end if;

    crear_tabla_si_falta(
        'cliente',
        q'~
            create table cliente (
                cliente_id number(12)
                    generated by default on null as identity
                    (start with 1 increment by 1 cache 100),
                nombre               varchar2(40 char)  not null,
                apellido_paterno     varchar2(40 char)  not null,
                apellido_materno     varchar2(40 char),
                fecha_nacimiento     date               not null,
                sexo                 char(1 char)       not null,
                identificador_fiscal varchar2(40 char)  not null,
                email                varchar2(250 char) not null,
                contrasena           varchar2(255 char) not null,
                foto                 blob               not null,
                genero_id            number(12),
                constraint pk_cliente primary key (cliente_id),
                constraint uk_cliente_identificador_fiscal unique (identificador_fiscal),
                constraint uk_cliente_email unique (email),
                constraint fk_cliente_genero
                    foreign key (genero_id) references genero (genero_id),
                constraint ck_cliente_sexo
                    check (sexo in ('M', 'F', 'X')),
                constraint ck_cliente_fecha_nacimiento
                    check (fecha_nacimiento >= date '1900-01-01'),
                constraint ck_cliente_fiscal_normalizado
                    check (identificador_fiscal = upper(trim(identificador_fiscal))),
                constraint ck_cliente_email_normalizado
                    check (email = lower(trim(email))),
                constraint ck_cliente_contrasena_hash
                    check (length(contrasena) >= 60)
            )
        ~'
    );

    crear_tabla_si_falta(
        'tarjeta',
        q'~
            create table tarjeta (
                tarjeta_id number(12)
                    generated by default on null as identity
                    (start with 1 increment by 1 cache 100),
                cliente_id        number(12) not null,
                tipo_tarjeta_id   number(12) not null,
                numero_tarjeta    raw(128)   not null,
                anio_expiracion   number(4)  not null,
                mes_expiracion    number(2)  not null,
                constraint pk_tarjeta primary key (tarjeta_id),
                constraint fk_tarjeta_cliente
                    foreign key (cliente_id) references cliente (cliente_id),
                constraint fk_tarjeta_tipo
                    foreign key (tipo_tarjeta_id) references tipo_tarjeta (tipo_tarjeta_id),
                constraint ck_tarjeta_anio_expiracion
                    check (anio_expiracion between 2000 and 9999),
                constraint ck_tarjeta_mes_expiracion
                    check (mes_expiracion between 1 and 12)
            )
        ~'
    );

    crear_indice_si_falta(
        'ix_cliente_genero',
        'create index ix_cliente_genero on cliente (genero_id)'
    );

    crear_indice_si_falta(
        'ix_tarjeta_cliente',
        'create index ix_tarjeta_cliente on tarjeta (cliente_id)'
    );

    crear_indice_si_falta(
        'ix_tarjeta_tipo',
        'create index ix_tarjeta_tipo on tarjeta (tipo_tarjeta_id)'
    );
end;
