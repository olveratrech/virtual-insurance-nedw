-- proposito: crear solicitudes de cancelacion y sincronizar sus estados con poliza.
-- conexion requerida: vi_app@etobda_s1

set serveroutput on

declare
    v_usuario     varchar2(128);
    v_contenedor  varchar2(128);
    v_existe      number;

    procedure crear_indice_si_falta(
        p_indice    varchar2,
        p_sentencia varchar2
    ) is
        v_indice_existe number;
    begin
        select count(*) into v_indice_existe
          from user_indexes
         where index_name = upper(p_indice);

        if v_indice_existe = 0 then
            execute immediate p_sentencia;
            dbms_output.put_line('creado: ' || lower(p_indice));
        else
            dbms_output.put_line('conservado: ' || lower(p_indice));
        end if;
    end crear_indice_si_falta;
begin
    v_usuario := sys_context('USERENV', 'CURRENT_USER');
    v_contenedor := sys_context('USERENV', 'CON_NAME');

    if v_usuario <> 'VI_APP' or v_contenedor <> 'ETOBDA_S1' then
        raise_application_error(
            -20010,
            'conexion incorrecta. se esperaba VI_APP@ETOBDA_S1 y se obtuvo '
            || v_usuario || '@' || v_contenedor
        );
    end if;

    select count(*) into v_existe
      from user_tables
     where table_name = 'SOLICITUD_CANCELACION';

    if v_existe = 0 then
        execute immediate q'~
            create table solicitud_cancelacion (
                solicitud_cancelacion_id number(12)
                    generated by default on null as identity
                    (start with 1 increment by 1 cache 100),
                poliza_id                  number(12)                        not null,
                folio                     varchar2(20 char)                 not null,
                motivo                    varchar2(20 char)                 not null,
                fecha_solicitada          date                              not null,
                comentarios               varchar2(500 char),
                estatus_cancelacion_id    number(12)                        not null,
                fecha_creacion            timestamp(6) with local time zone not null,
                fecha_resolucion          timestamp(6) with local time zone,
                observacion_resolucion    varchar2(500 char),
                constraint pk_solicitud_cancelacion primary key
                    (solicitud_cancelacion_id),
                constraint uk_solicitud_cancelacion_folio unique (folio),
                constraint fk_solicitud_cancelacion_pol
                    foreign key (poliza_id) references poliza (poliza_id),
                constraint fk_solicitud_cancelacion_est
                    foreign key (estatus_cancelacion_id)
                    references estatus_cancelacion (estatus_cancelacion_id),
                constraint ck_solicitud_cancelacion_motivo
                    check (motivo in ('NOT_NEEDED', 'FINANCIAL', 'SERVICE', 'OTHER'))
            )
        ~';
        dbms_output.put_line('creada: solicitud_cancelacion');
    else
        dbms_output.put_line('conservada: solicitud_cancelacion');
    end if;

    crear_indice_si_falta(
        'ix_solicitud_cancelacion_pol',
        'create index ix_solicitud_cancelacion_pol on solicitud_cancelacion (poliza_id)'
    );
    crear_indice_si_falta(
        'ix_solicitud_cancelacion_est',
        'create index ix_solicitud_cancelacion_est on solicitud_cancelacion (estatus_cancelacion_id)'
    );
end;
/

create or replace trigger trg_solicitud_cancelacion_reg
for insert or update or delete on solicitud_cancelacion
compound trigger
    v_solicitada_id estatus_cancelacion.estatus_cancelacion_id%type;

    before statement is
    begin
        select estatus_cancelacion_id into v_solicitada_id
          from estatus_cancelacion
         where clave = 'SOLICITADA';
    end before statement;

    before each row is
        v_estatus_anterior estatus_cancelacion.clave%type;
        v_estatus_nuevo    estatus_cancelacion.clave%type;
        v_estatus_poliza   estatus_poliza.clave%type;
    begin
        if deleting then
            raise_application_error(-20080, 'una solicitud de cancelacion no se puede eliminar.');
        end if;

        select ep.clave
          into v_estatus_poliza
          from poliza p
          join estatus_poliza ep
            on ep.estatus_poliza_id = p.estatus_poliza_id
         where p.poliza_id = :new.poliza_id
           for update of p.estatus_poliza_id;

        select clave into v_estatus_nuevo
          from estatus_cancelacion
         where estatus_cancelacion_id = :new.estatus_cancelacion_id;

        if inserting then
            if v_estatus_nuevo <> 'SOLICITADA' then
                raise_application_error(-20081, 'una solicitud nueva debe iniciar solicitada.');
            end if;

            if v_estatus_poliza <> 'ACTIVA' then
                raise_application_error(-20082, 'solo una poliza activa admite una solicitud de cancelacion.');
            end if;

            if :new.fecha_solicitada < trunc(current_date) then
                raise_application_error(-20083, 'la fecha solicitada no puede estar en el pasado.');
            end if;

            if :new.fecha_creacion is null then
                :new.fecha_creacion := systimestamp;
            end if;

            if :new.fecha_resolucion is not null
                or :new.observacion_resolucion is not null then
                raise_application_error(-20084, 'una solicitud pendiente no admite datos de resolucion.');
            end if;
        else
            if :new.poliza_id <> :old.poliza_id
                or :new.folio <> :old.folio
                or :new.motivo <> :old.motivo
                or :new.fecha_solicitada <> :old.fecha_solicitada
                or nvl(:new.comentarios, chr(0)) <> nvl(:old.comentarios, chr(0))
                or :new.fecha_creacion <> :old.fecha_creacion then
                raise_application_error(-20085, 'los datos originales de la solicitud no se pueden modificar.');
            end if;

            select clave into v_estatus_anterior
              from estatus_cancelacion
             where estatus_cancelacion_id = :old.estatus_cancelacion_id;

            if v_estatus_anterior <> 'SOLICITADA'
                or v_estatus_nuevo not in ('APROBADA', 'RECHAZADA') then
                raise_application_error(-20086, 'transicion de cancelacion no permitida.');
            end if;

            if v_estatus_poliza <> 'CANCELACION_SOLICITADA' then
                raise_application_error(-20087, 'la poliza no tiene una cancelacion pendiente.');
            end if;

            if :new.fecha_resolucion is null then
                :new.fecha_resolucion := systimestamp;
            end if;
        end if;
    end before each row;

    after each row is
        v_estatus_poliza_id estatus_poliza.estatus_poliza_id%type;
    begin
        if inserting then
            select estatus_poliza_id into v_estatus_poliza_id
              from estatus_poliza
             where clave = 'CANCELACION_SOLICITADA';
        elsif updating then
            select ep.estatus_poliza_id into v_estatus_poliza_id
              from estatus_cancelacion ec
              join estatus_poliza ep
                on ep.clave = case ec.clave
                    when 'APROBADA' then 'CANCELADA'
                    when 'RECHAZADA' then 'ACTIVA'
                    else 'CANCELACION_SOLICITADA'
                end
             where ec.estatus_cancelacion_id = :new.estatus_cancelacion_id;
        end if;

        update poliza
           set estatus_poliza_id = v_estatus_poliza_id
         where poliza_id = :new.poliza_id;
    end after each row;

    after statement is
        v_duplicados number;
    begin
        select count(*) into v_duplicados
          from (
                select poliza_id
                  from solicitud_cancelacion
                 where estatus_cancelacion_id = v_solicitada_id
                 group by poliza_id
                having count(*) > 1
          );

        if v_duplicados > 0 then
            raise_application_error(-20088, 'una poliza no puede tener dos solicitudes pendientes.');
        end if;
    end after statement;
end;
/
