declare
    v_usuario    varchar2(128);
    v_contenedor varchar2(128);

    procedure crear_tabla_si_falta(p_tabla varchar2, p_sentencia varchar2) is
        v_existe number;
    begin
        select count(*) into v_existe
          from user_tables
         where table_name = upper(p_tabla);

        if v_existe = 0 then
            execute immediate p_sentencia;
            dbms_output.put_line('creada: ' || lower(p_tabla));
        else
            dbms_output.put_line('conservada: ' || lower(p_tabla));
        end if;
    end crear_tabla_si_falta;

    procedure agregar_columna_si_falta(
        p_tabla varchar2,
        p_columna varchar2,
        p_definicion varchar2
    ) is
        v_existe number;
    begin
        select count(*) into v_existe
          from user_tab_columns
         where table_name = upper(p_tabla)
           and column_name = upper(p_columna);

        if v_existe = 0 then
            execute immediate 'alter table ' || dbms_assert.simple_sql_name(p_tabla)
                || ' add (' || p_definicion || ')';
            dbms_output.put_line('agregada: ' || lower(p_tabla) || '.' || lower(p_columna));
        else
            dbms_output.put_line('conservada: ' || lower(p_tabla) || '.' || lower(p_columna));
        end if;
    end agregar_columna_si_falta;

    procedure crear_restriccion_si_falta(p_nombre varchar2, p_sentencia varchar2) is
        v_existe number;
    begin
        select count(*) into v_existe
          from user_constraints
         where constraint_name = upper(p_nombre);

        if v_existe = 0 then
            execute immediate p_sentencia;
            dbms_output.put_line('creada: ' || lower(p_nombre));
        else
            dbms_output.put_line('conservada: ' || lower(p_nombre));
        end if;
    end crear_restriccion_si_falta;

    procedure crear_indice_si_falta(p_nombre varchar2, p_sentencia varchar2) is
        v_existe number;
    begin
        select count(*) into v_existe
          from user_indexes
         where index_name = upper(p_nombre);

        if v_existe = 0 then
            execute immediate p_sentencia;
            dbms_output.put_line('creado: ' || lower(p_nombre));
        else
            dbms_output.put_line('conservado: ' || lower(p_nombre));
        end if;
    end crear_indice_si_falta;
begin
    v_usuario := sys_context('USERENV', 'CURRENT_USER');
    v_contenedor := sys_context('USERENV', 'CON_NAME');

    if v_usuario <> 'VI_APP' or v_contenedor <> 'ETOBDA_S1' then
        raise_application_error(
            -20010,
            'conexion incorrecta. se esperaba VI_APP@ETOBDA_S1 y se obtuvo '
            || v_usuario || '@' || v_contenedor
        );
    end if;

    crear_tabla_si_falta(
        'rol_interno',
        q'~
            create table rol_interno (
                rol_interno_id number(12)
                    generated by default on null as identity
                    (start with 1 increment by 1 cache 20),
                clave       varchar2(40 char)  not null,
                descripcion varchar2(200 char) not null,
                constraint pk_rol_interno primary key (rol_interno_id),
                constraint uk_rol_interno_clave unique (clave),
                constraint ck_rol_interno_clave
                    check (clave = upper(trim(clave)))
            )
        ~'
