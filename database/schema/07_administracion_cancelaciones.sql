    crear_tabla_si_falta(
        'usuario_interno',
        q'~
            create table usuario_interno (
                usuario_interno_id number(12)
                    generated by default on null as identity
                    (start with 1 increment by 1 cache 20),
                nombre         varchar2(120 char)                 not null,
                email          varchar2(250 char)                 not null,
                contrasena     varchar2(255 char)                 not null,
                activo         char(1 char) default 'S'           not null,
                fecha_creacion timestamp(6) with local time zone not null,
                ultimo_acceso  timestamp(6) with local time zone,
                constraint pk_usuario_interno primary key (usuario_interno_id),
                constraint uk_usuario_interno_email unique (email),
                constraint ck_usuario_interno_email
                    check (email = lower(trim(email))),
                constraint ck_usuario_interno_hash
                    check (length(contrasena) >= 60),
                constraint ck_usuario_interno_activo
                    check (activo in ('S', 'N'))
