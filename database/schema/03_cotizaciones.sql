create or replace trigger trg_cotizacion_auto_tipo
    before insert or update of cotizacion_id on cotizacion_auto
    for each row
declare
    v_tipo cotizacion.tipo_seguro%type;
begin
    select tipo_seguro into v_tipo
      from cotizacion
     where cotizacion_id = :new.cotizacion_id;

    if v_tipo <> 'A' then
        raise_application_error(-20041, 'el subtipo auto requiere una cotizacion de tipo A.');
    end if;
exception
    when no_data_found then
        raise_application_error(-20042, 'la cotizacion asociada al subtipo auto no existe.');
end;
/

