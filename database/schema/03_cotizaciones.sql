create or replace trigger trg_cotizacion_cambio_tipo
    before update of tipo_seguro on cotizacion
    for each row
declare
    v_existe number;
begin
    if :new.tipo_seguro <> :old.tipo_seguro then
        if :new.tipo_seguro = 'A' then
            select count(*) into v_existe
              from cotizacion_medica
             where cotizacion_id = :old.cotizacion_id;
        else
            select count(*) into v_existe
              from cotizacion_auto
             where cotizacion_id = :old.cotizacion_id;
        end if;

        if v_existe > 0 then
            raise_application_error(
                -20045,
                'no se puede cambiar el tipo mientras exista un subtipo incompatible.'
            );
        end if;
    end if;
end;
/

create or replace trigger trg_cotizacion_historial
    after insert or update of estatus_cotizacion_id on cotizacion
    for each row
declare
    v_numero_cambio number(10);
begin
    if inserting then
        v_numero_cambio := 1;
    elsif :new.estatus_cotizacion_id = :old.estatus_cotizacion_id then
        return;
    else
        select nvl(max(numero_cambio), 0) + 1
          into v_numero_cambio
          from historico_estatus_cotizacion
         where cotizacion_id = :new.cotizacion_id;
    end if;

    insert into historico_estatus_cotizacion (
        numero_cambio,
        fecha_cambio,
        estatus_cotizacion_id,
        cotizacion_id
    ) values (
        v_numero_cambio,
        systimestamp,
        :new.estatus_cotizacion_id,
        :new.cotizacion_id
    );
end;
