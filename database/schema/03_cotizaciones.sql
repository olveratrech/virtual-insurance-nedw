set serveroutput on

declare
    v_usuario     varchar2(128);
    v_contenedor  varchar2(128);

    procedure crear_tabla_si_falta(
        p_tabla     varchar2,
        p_sentencia varchar2
    ) is
        v_existe number;
    begin
        select count(*) into v_existe
          from user_tables
         where table_name = upper(p_tabla);

        if v_existe = 0 then
            execute immediate p_sentencia;
            dbms_output.put_line('creada: ' || lower(p_tabla));
        else
            dbms_output.put_line('conservada: ' || lower(p_tabla));
        end if;
    end crear_tabla_si_falta;

    procedure crear_indice_si_falta(
        p_indice    varchar2,
        p_sentencia varchar2
    ) is
        v_existe number;
    begin
        select count(*) into v_existe
          from user_indexes
         where index_name = upper(p_indice);

        if v_existe = 0 then
            execute immediate p_sentencia;
            dbms_output.put_line('creado: ' || lower(p_indice));
        else
            dbms_output.put_line('conservado: ' || lower(p_indice));
        end if;
    end crear_indice_si_falta;
begin
    v_usuario := sys_context('USERENV', 'CURRENT_USER');
    v_contenedor := sys_context('USERENV', 'CON_NAME');

    if v_usuario <> 'VI_APP' or v_contenedor <> 'ETOBDA_S1' then
        raise_application_error(
            -20010,
            'conexion incorrecta. se esperaba VI_APP@ETOBDA_S1 y se obtuvo '
            || v_usuario || '@' || v_contenedor
        );
    end if;

    crear_tabla_si_falta(
        'cotizacion',
        q'~
            create table cotizacion (
                cotizacion_id number(12)
                    generated by default on null as identity
                    (start with 1 increment by 1 cache 100),
                cliente_id              number(12)                        not null,
                numero_cotizacion       number(4)                         not null,
                fecha_cotizacion        timestamp(6) with local time zone not null,
                vigencia_cotizacion     date                              not null,
                tipo_seguro             char(1 char)                      not null,
                costo_calculado         number(14,2),
                rechazo_pdf             blob,
                estatus_cotizacion_id   number(12)                        not null,
                constraint pk_cotizacion primary key (cotizacion_id),
                constraint uk_cotizacion_numero unique (numero_cotizacion),
                constraint fk_cotizacion_cliente
                    foreign key (cliente_id) references cliente (cliente_id),
                constraint fk_cotizacion_estatus
                    foreign key (estatus_cotizacion_id)
                    references estatus_cotizacion (estatus_cotizacion_id),
                constraint ck_cotizacion_tipo
                    check (tipo_seguro in ('A', 'M')),
                constraint ck_cotizacion_costo
                    check (costo_calculado is null or costo_calculado >= 0)
            )
        ~'
    );

    crear_tabla_si_falta(
        'cotizacion_auto',
        q'~
            create table cotizacion_auto (
                cotizacion_id         number(12)        not null,
                marca                 varchar2(40 char) not null,
                modelo                varchar2(40 char) not null,
                anio                  number(4)         not null,
                categoria             varchar2(10 char) not null,
                placas                varchar2(20 char) not null,
                numero_licencia       varchar2(40 char) not null,
                edad_conductor        number(3)         not null,
                puntos_negativos      number(5)         not null,
                antecedentes_penales char(1 char)      not null,
                constraint pk_cotizacion_auto primary key (cotizacion_id),
                constraint fk_cotizacion_auto_cotizacion
                    foreign key (cotizacion_id) references cotizacion (cotizacion_id),
                constraint ck_cotizacion_auto_anio
                    check (anio between 1980 and 9999),
                constraint ck_cotizacion_auto_categoria
                    check (categoria in ('SEDAN', 'SUV', 'PICKUP', 'OTHER')),
                constraint ck_cotizacion_auto_edad
                    check (edad_conductor between 18 and 90),
                constraint ck_cotizacion_auto_puntos
                    check (puntos_negativos >= 0),
                constraint ck_cotizacion_auto_antecedentes
                    check (antecedentes_penales in ('S', 'N'))
            )
        ~'
    );

    crear_tabla_si_falta(
        'cotizacion_medica',
        q'~
            create table cotizacion_medica (
                cotizacion_id          number(12)   not null,
                edad_asegurado         number(3)    not null,
                hipertension           char(1 char) not null,
                glucosa_fuera_rango    char(1 char) not null,
                colesterol_fuera_rango char(1 char) not null,
                fumador                char(1 char) not null,
                adiccion_alcohol       char(1 char) not null,
                constraint pk_cotizacion_medica primary key (cotizacion_id),
                constraint fk_cotizacion_medica_cotizacion
                    foreign key (cotizacion_id) references cotizacion (cotizacion_id),
                constraint ck_cotizacion_medica_edad
                    check (edad_asegurado between 18 and 100),
                constraint ck_cotizacion_medica_hipertension
                    check (hipertension in ('S', 'N')),
                constraint ck_cotizacion_medica_glucosa
                    check (glucosa_fuera_rango in ('S', 'N')),
                constraint ck_cotizacion_medica_colesterol
                    check (colesterol_fuera_rango in ('S', 'N')),
                constraint ck_cotizacion_medica_fumador
                    check (fumador in ('S', 'N')),
                constraint ck_cotizacion_medica_alcohol
                    check (adiccion_alcohol in ('S', 'N'))
            )
        ~'
    );

    crear_tabla_si_falta(
        'historico_estatus_cotizacion',
        q'~
            create table historico_estatus_cotizacion (
                historico_estatus_cotizacion_id number(12)
                    generated by default on null as identity
                    (start with 1 increment by 1 cache 100),
                numero_cambio          number(10)                        not null,
                fecha_cambio           timestamp(6) with local time zone not null,
                estatus_cotizacion_id  number(12)                        not null,
                cotizacion_id          number(12)                        not null,
                constraint pk_historico_estatus_cot primary key
                    (historico_estatus_cotizacion_id),
                constraint uk_historico_estatus_cot_cambio unique
                    (cotizacion_id, numero_cambio),
                constraint fk_historico_estatus_cot_est
                    foreign key (estatus_cotizacion_id)
                    references estatus_cotizacion (estatus_cotizacion_id),
                constraint fk_historico_estatus_cot_cot
                    foreign key (cotizacion_id) references cotizacion (cotizacion_id),
                constraint ck_historico_estatus_cot_numero
                    check (numero_cambio > 0)
            )
        ~'
    );

    crear_indice_si_falta(
        'ix_cotizacion_cliente',
        'create index ix_cotizacion_cliente on cotizacion (cliente_id)'
    );
    crear_indice_si_falta(
        'ix_cotizacion_estatus',
        'create index ix_cotizacion_estatus on cotizacion (estatus_cotizacion_id)'
    );
    crear_indice_si_falta(
        'ix_historico_cot_estatus',
        'create index ix_historico_cot_estatus on historico_estatus_cotizacion (estatus_cotizacion_id)'
    );
end;
