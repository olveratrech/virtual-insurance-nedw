create or replace trigger trg_intento_pago_reglas
for insert or update on intento_pago
compound trigger
    before each row is
        v_estatus_cotizacion_id cotizacion.estatus_cotizacion_id%type;
        v_estatus_cotizacion    estatus_cotizacion.clave%type;
        v_estatus_intento       estatus_intento_pago.clave%type;
    begin
        select estatus_cotizacion_id
          into v_estatus_cotizacion_id
          from cotizacion
         where cotizacion_id = :new.cotizacion_id
           for update;

        select clave into v_estatus_cotizacion
          from estatus_cotizacion
         where estatus_cotizacion_id = v_estatus_cotizacion_id;

        if v_estatus_cotizacion <> 'APROBADA' then
            raise_application_error(-20060, 'solo una cotizacion aprobada puede recibir intentos de pago.');
        end if;

        select clave into v_estatus_intento
          from estatus_intento_pago
         where estatus_intento_pago_id = :new.estatus_intento_pago_id;

        if v_estatus_intento = 'APROBADO' then
            if :new.motivo_rechazo is not null or :new.comprobante_pdf is null then
                raise_application_error(-20061, 'un intento aprobado requiere comprobante y no admite motivo de rechazo.');
            end if;
        elsif v_estatus_intento = 'RECHAZADO' then
            if :new.motivo_rechazo is null or :new.comprobante_pdf is not null then
                raise_application_error(-20062, 'un intento rechazado requiere motivo y no admite comprobante.');
            end if;
        elsif :new.motivo_rechazo is not null or :new.comprobante_pdf is not null then
            raise_application_error(-20063, 'un intento pendiente no admite resultado ni comprobante.');
        end if;
    end before each row;

    after statement is
        v_duplicados number;
    begin
        select count(*)
          into v_duplicados
          from (
                select i.cotizacion_id
                  from intento_pago i
                  join estatus_intento_pago e
                    on e.estatus_intento_pago_id = i.estatus_intento_pago_id
                 where e.clave = 'APROBADO'
                 group by i.cotizacion_id
                having count(*) > 1
          );

        if v_duplicados > 0 then
            raise_application_error(-20064, 'una cotizacion no puede tener mas de un intento aprobado.');
        end if;
    end after statement;
end;
/

create or replace trigger trg_poliza_reglas
    before insert or update on poliza
    for each row
declare
    v_estatus_intento  estatus_intento_pago.clave%type;
    v_modalidad        intento_pago.modalidad_pago_id%type;
    v_costo            cotizacion.costo_calculado%type;
    v_estatus_nuevo    estatus_poliza.clave%type;
    v_estatus_anterior estatus_poliza.clave%type;
begin
    select e.clave, i.modalidad_pago_id, c.costo_calculado
      into v_estatus_intento, v_modalidad, v_costo
      from intento_pago i
      join estatus_intento_pago e
        on e.estatus_intento_pago_id = i.estatus_intento_pago_id
      join cotizacion c
        on c.cotizacion_id = i.cotizacion_id
     where i.intento_pago_id = :new.intento_pago_id;

    if v_estatus_intento <> 'APROBADO' then
        raise_application_error(-20065, 'una poliza requiere un intento de pago aprobado.');
    end if;

    if :new.modalidad_pago_id <> v_modalidad then
        raise_application_error(-20066, 'la modalidad de la poliza debe coincidir con la del intento.');
    end if;

    if v_costo is null or :new.costo_seguro <> v_costo then
        raise_application_error(-20067, 'el costo de la poliza debe coincidir con la cotizacion.');
    end if;

    select clave into v_estatus_nuevo
      from estatus_poliza
     where estatus_poliza_id = :new.estatus_poliza_id;

    if inserting then
        if v_estatus_nuevo <> 'ACTIVA' then
            raise_application_error(-20068, 'una poliza nueva debe iniciar activa.');
        end if;
    elsif :new.estatus_poliza_id <> :old.estatus_poliza_id then
        select clave into v_estatus_anterior
          from estatus_poliza
         where estatus_poliza_id = :old.estatus_poliza_id;

        if not (
            (v_estatus_anterior = 'ACTIVA'
                and v_estatus_nuevo in ('CANCELACION_SOLICITADA', 'VENCIDA'))
            or
            (v_estatus_anterior = 'CANCELACION_SOLICITADA'
                and v_estatus_nuevo in ('ACTIVA', 'CANCELADA'))
        ) then
            raise_application_error(-20069, 'transicion de estatus de poliza no permitida.');
        end if;
    end if;
end;
/

create or replace trigger trg_poliza_historial
    after insert or update of estatus_poliza_id on poliza
    for each row
declare
    v_numero_cambio number(10);
begin
    if inserting then
        v_numero_cambio := 1;
    elsif :new.estatus_poliza_id = :old.estatus_poliza_id then
        return;
    else
        select nvl(max(numero_cambio), 0) + 1
          into v_numero_cambio
          from historico_estatus_poliza
         where poliza_id = :new.poliza_id;
    end if;

    insert into historico_estatus_poliza (
        numero_cambio,
        fecha_cambio,
        estatus_poliza_id,
        poliza_id
    ) values (
        v_numero_cambio,
        systimestamp,
        :new.estatus_poliza_id,
        :new.poliza_id
    );
end;
