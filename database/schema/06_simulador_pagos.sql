-- conexion requerida: vi_app@etobda_s1

set serveroutput on

declare
    v_usuario     varchar2(128);
    v_contenedor  varchar2(128);

    procedure crear_tabla_si_falta(p_tabla varchar2, p_sentencia varchar2) is
        v_existe number;
    begin
        select count(*) into v_existe from user_tables where table_name = upper(p_tabla);
        if v_existe = 0 then
            execute immediate p_sentencia;
            dbms_output.put_line('creada: ' || lower(p_tabla));
        else
            dbms_output.put_line('conservada: ' || lower(p_tabla));
        end if;
    end;

    procedure agregar_columna_si_falta(
        p_tabla varchar2,
        p_columna varchar2,
        p_definicion varchar2
    ) is
        v_existe number;
    begin
        select count(*) into v_existe
          from user_tab_columns
         where table_name = upper(p_tabla)
           and column_name = upper(p_columna);
        if v_existe = 0 then
            execute immediate 'alter table ' || dbms_assert.simple_sql_name(p_tabla)
                || ' add (' || p_definicion || ')';
            dbms_output.put_line('agregada: ' || lower(p_tabla) || '.' || lower(p_columna));
        else
            dbms_output.put_line('conservada: ' || lower(p_tabla) || '.' || lower(p_columna));
        end if;
    end;

    procedure crear_restriccion_si_falta(
        p_nombre varchar2,
        p_sentencia varchar2
    ) is
        v_existe number;
    begin
        select count(*) into v_existe
          from user_constraints
         where constraint_name = upper(p_nombre);
        if v_existe = 0 then
            execute immediate p_sentencia;
            dbms_output.put_line('creada: ' || lower(p_nombre));
        else
            dbms_output.put_line('conservada: ' || lower(p_nombre));
        end if;
    end;

    procedure crear_secuencia_si_falta(
        p_nombre varchar2,
        p_sentencia varchar2
    ) is
        v_existe number;
    begin
        select count(*) into v_existe
          from user_sequences
         where sequence_name = upper(p_nombre);
        if v_existe = 0 then
            execute immediate p_sentencia;
            dbms_output.put_line('creada: ' || lower(p_nombre));
        else
            dbms_output.put_line('conservada: ' || lower(p_nombre));
        end if;
    end;
begin
    v_usuario := sys_context('USERENV', 'CURRENT_USER');
    v_contenedor := sys_context('USERENV', 'CON_NAME');

    if v_usuario <> 'VI_APP' or v_contenedor <> 'ETOBDA_S1' then
        raise_application_error(
            -20010,
            'conexion incorrecta. se esperaba VI_APP@ETOBDA_S1 y se obtuvo '
            || v_usuario || '@' || v_contenedor
        );
    end if;

    crear_tabla_si_falta(
        'instrumento_pago_prueba',
        q'~
            create table instrumento_pago_prueba (
                instrumento_pago_prueba_id number(12)
                    generated by default on null as identity
                    (start with 1 increment by 1 cache 20),
                token                    varchar2(64 char)  not null,
                numero_hash              varchar2(64 char)  not null,
                ultimos_cuatro            char(4 char)       not null,
                saldo_disponible          number(14,2)       not null,
                estatus                   varchar2(20 char)  not null,
                anio_expiracion           number(4)          not null,
                mes_expiracion            number(2)          not null,
                respuesta_forzada         varchar2(40 char),
                version                   number(10) default 0 not null,
                constraint pk_instrumento_pago_prueba
                    primary key (instrumento_pago_prueba_id),
                constraint uk_instrumento_pago_token unique (token),
                constraint uk_instrumento_pago_hash unique (numero_hash),
                constraint ck_instrumento_pago_saldo check (saldo_disponible >= 0),
                constraint ck_instrumento_pago_estatus
                    check (estatus in ('ACTIVE', 'BLOCKED')),
                constraint ck_instrumento_pago_anio
                    check (anio_expiracion between 2000 and 9999),
                constraint ck_instrumento_pago_mes
                    check (mes_expiracion between 1 and 12),
                constraint ck_instrumento_pago_respuesta
                    check (respuesta_forzada is null or respuesta_forzada = 'PROCESSOR_DECLINED'),
                constraint ck_instrumento_pago_version check (version >= 0)
            )
        ~'
    );

    agregar_columna_si_falta(
        'intento_pago', 'idempotency_key', 'idempotency_key varchar2(64 char)'
    );
    agregar_columna_si_falta(
        'intento_pago', 'codigo_respuesta', 'codigo_respuesta varchar2(40 char)'
    );
    agregar_columna_si_falta(
        'intento_pago', 'codigo_autorizacion', 'codigo_autorizacion varchar2(40 char)'
    );

    execute immediate 'alter table intento_pago modify (numero_pago number(10))';
    dbms_output.put_line('precision verificada: intento_pago.numero_pago number(10)');

    crear_restriccion_si_falta(
        'uk_intento_pago_idempotency',
        'alter table intento_pago add constraint uk_intento_pago_idempotency unique (idempotency_key)'
    );

    crear_secuencia_si_falta(
        'seq_numero_pago',
        'create sequence seq_numero_pago start with 1000 increment by 1 cache 50 nocycle'
    );
    crear_secuencia_si_falta(
        'seq_folio_poliza',
        'create sequence seq_folio_poliza start with 1000 increment by 1 cache 50 nocycle'
    );
end;
