-- conexion requerida: vi_app@etobda_s1

set serveroutput on

declare
    v_usuario     varchar2(128);
    v_contenedor  varchar2(128);

    procedure crear_tabla_si_falta(
        p_tabla     varchar2,
        p_sentencia varchar2
    ) is
        v_existe number;
    begin
        select count(*)
          into v_existe
          from user_tables
         where table_name = upper(p_tabla);

        if v_existe = 0 then
            execute immediate p_sentencia;
            dbms_output.put_line('creada: ' || lower(p_tabla));
        else
            dbms_output.put_line('conservada: ' || lower(p_tabla));
        end if;
    end crear_tabla_si_falta;
begin
    v_usuario := sys_context('USERENV', 'CURRENT_USER');
    v_contenedor := sys_context('USERENV', 'CON_NAME');

    if v_usuario <> 'VI_APP' or v_contenedor <> 'ETOBDA_S1' then
        raise_application_error(
            -20010,
            'conexion incorrecta. se esperaba VI_APP@ETOBDA_S1 y se obtuvo '
            || v_usuario || '@' || v_contenedor
        );
    end if;

    crear_tabla_si_falta(
        'genero',
        q'~
            create table genero (
                genero_id number(12)
                    generated by default on null as identity
                    (start with 1 increment by 1 cache 100),
                clave       varchar2(20 char)  not null,
                descripcion varchar2(100 char) not null,
                constraint pk_genero primary key (genero_id),
                constraint uk_genero_clave unique (clave)
            )
        ~'
    );

    crear_tabla_si_falta(
        'tipo_tarjeta',
        q'~
            create table tipo_tarjeta (
                tipo_tarjeta_id number(12)
                    generated by default on null as identity
                    (start with 1 increment by 1 cache 100),
                clave       varchar2(20 char) not null,
                descripcion varchar2(60 char) not null,
                constraint pk_tipo_tarjeta primary key (tipo_tarjeta_id),
                constraint uk_tipo_tarjeta_clave unique (clave)
            )
        ~'
    );

    crear_tabla_si_falta(
        'modalidad_pago',
        q'~
            create table modalidad_pago (
                modalidad_pago_id number(12)
                    generated by default on null as identity
                    (start with 1 increment by 1 cache 100),
                clave           varchar2(10 char) not null,
                intervalo_meses number(2)         not null,
                constraint pk_modalidad_pago primary key (modalidad_pago_id),
                constraint uk_modalidad_pago_clave unique (clave),
                constraint ck_modalidad_pago_intervalo
                    check (intervalo_meses between 1 and 99)
            )
        ~'
    );

    crear_tabla_si_falta(
        'estatus_cotizacion',
        q'~
            create table estatus_cotizacion (
                estatus_cotizacion_id number(12)
                    generated by default on null as identity
                    (start with 1 increment by 1 cache 100),
                descripcion varchar2(100 char) not null,
                clave       varchar2(20 char)  not null,
                constraint pk_estatus_cotizacion primary key (estatus_cotizacion_id),
                constraint uk_estatus_cotizacion_clave unique (clave)
            )
        ~'
    );

    crear_tabla_si_falta(
        'estatus_intento_pago',
        q'~
            create table estatus_intento_pago (
                estatus_intento_pago_id number(12)
                    generated by default on null as identity
                    (start with 1 increment by 1 cache 100),
                clave       varchar2(20 char)  not null,
                descripcion varchar2(100 char) not null,
                constraint pk_estatus_intento_pago primary key (estatus_intento_pago_id),
                constraint uk_estatus_intento_pago_clave unique (clave)
            )
        ~'
    );

    crear_tabla_si_falta(
        'estatus_poliza',
        q'~
            create table estatus_poliza (
                estatus_poliza_id number(12)
                    generated by default on null as identity
                    (start with 1 increment by 1 cache 100),
                clave       varchar2(30 char)  not null,
                descripcion varchar2(100 char) not null,
                constraint pk_estatus_poliza primary key (estatus_poliza_id),
                constraint uk_estatus_poliza_clave unique (clave)
            )
        ~'
    );

    crear_tabla_si_falta(
        'estatus_cancelacion',
        q'~
            create table estatus_cancelacion (
                estatus_cancelacion_id number(12)
                    generated by default on null as identity
                    (start with 1 increment by 1 cache 100),
                clave       varchar2(20 char)  not null,
                descripcion varchar2(100 char) not null,
                constraint pk_estatus_cancelacion primary key (estatus_cancelacion_id),
                constraint uk_estatus_cancelacion_clave unique (clave)
            )
        ~'
    );
end;
